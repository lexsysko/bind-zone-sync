class TestConvert(unittest.TestCase):
    """Test the convert command — zone db folder to legacy named.conf."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        # Create a zone directory with db files
        self.zone_dir = Path(self.tmp) / "zones"
        self.zone_dir.mkdir()

        # Copy fixture db files
        shutil.copy(FIXTURES / "app1.example.net.db", self.zone_dir / "app1.example.net.db")
        shutil.copy(FIXTURES / "app2.example.net.db", self.zone_dir / "app2.example.net.db")
        shutil.copy(FIXTURES / "app3.example.net.db", self.zone_dir / "app3.example.net.db")

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def _convert_args(self, out: str, **kwargs) -> argparse.Namespace:
        defaults = dict(
            command="convert",
            conf=str(self.zone_dir),
            out=out,
            primaries="10.0.0.100;",
            db_path_find="",
            db_path_replace="",
            comment="// generated by bind-zone-sync, do not edit",
            log_level="INFO",
        )
        defaults.update(kwargs)
        return argparse.Namespace(**defaults)

    def test_convert_generates_secondary_conf_with_primaries(self):
        """Convert with --primaries should produce secondary zone blocks."""
        out = os.path.join(self.tmp, "out.conf")
        args = self._convert_args(out)
        convert(args)

        text = Path(out).read_text()
        self.assertIn('zone "app1.example.net"', text)
        self.assertIn('zone "app2.example.net"', text)
        self.assertIn('zone "app3.example.net"', text)
        self.assertIn("type secondary;", text)
        self.assertIn("primaries { 10.0.0.100; };", text)
        self.assertNotIn("type primary;", text)

    def test_convert_generates_primary_conf_without_primaries(self):
        """Convert without --primaries should produce primary zone blocks."""
        out = os.path.join(self.tmp, "out.conf")
        args = self._convert_args(out, primaries="")
        convert(args)

        text = Path(out).read_text()
        self.assertIn('zone "app1.example.net"', text)
        self.assertIn('zone "app2.example.net"', text)
        self.assertIn('zone "app3.example.net"', text)
        self.assertIn("type primary;", text)
        self.assertNotIn("type secondary;", text)
        self.assertNotIn("primaries {", text)

    def test_convert_includes_file_path(self):
        """Each zone block should reference the db file path."""
        out = os.path.join(self.tmp, "out.conf")
        args = self._convert_args(out)
        convert(args)

        text = Path(out).read_text()
        self.assertIn("app1.example.net.db", text)
        self.assertIn("app2.example.net.db", text)
        self.assertIn("app3.example.net.db", text)

    def test_convert_with_custom_primaries(self):
        """Custom primaries content should appear in output."""
        out = os.path.join(self.tmp, "out.conf")
        args = self._convert_args(out, primaries="192.168.1.1; 192.168.1.2;")
        convert(args)

        text = Path(out).read_text()
        self.assertIn("primaries { 192.168.1.1; 192.168.1.2; };", text)

    def test_convert_skips_hidden_files(self):
        """Hidden files (starting with .) should be skipped."""
        # Create a hidden db file
        hidden = self.zone_dir / ".hidden.db"
        hidden.write_text("$ORIGIN hidden.example.net.\n@ IN SOA ns1.hidden.example.net. admin.hidden.example.net. (\n            1 3600 900 604800 86400 )\n")

        out = os.path.join(self.tmp, "out.conf")
        args = self._convert_args(out)
        convert(args)

        text = Path(out).read_text()
        self.assertNotIn("hidden.example.net", text)

    def test_convert_nonexistent_directory(self):
        """Should not crash when directory doesn't exist."""
        out = os.path.join(self.tmp, "out.conf")
        args = self._convert_args(out, conf="/nonexistent/dir")
        convert(args)
        self.assertFalse(Path(out).exists())

    def test_convert_excludes_localhost(self):
        """Localhost zone should be excluded."""
        localhost_db = self.zone_dir / "localhost.db"
        localhost_db.write_text("$ORIGIN localhost.\n@ IN SOA ns1.localhost. admin.localhost. (\n            1 3600 900 604800 86400 )\n")

        out = os.path.join(self.tmp, "out.conf")
        args = self._convert_args(out)
        convert(args)

        text = Path(out).read_text()
        self.assertNotIn('zone "localhost"', text)

    def test_convert_with_custom_comment(self):
        """Custom comment should appear as the first line in output."""
